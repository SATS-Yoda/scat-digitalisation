def rebuild(conn: Connection) -> None:
    t.metadata.drop_all(conn)
    t.metadata.create_all(conn)
    seed(conn)


def is_disposable(url) -> bool:
    """True only for databases this module may wipe."""
    url = make_url(url)
    return url.drivername.startswith("sqlite") or url.database == DEV_DATABASE


def main() -> None:
    from .config import Settings

    url = Settings().database_url
    if not is_disposable(url):
        raise SystemExit(
            f"Refusing to seed: DATABASE_URL is neither SQLite nor the {DEV_DATABASE} database"
        )
    with create_engine(url).begin() as conn:
        rebuild(conn)
    print("Seeded synthetic data")


if __name__ == "__main__":
    main()
