"""Synthetic data for local development and tests. Nothing here is real operational data.

    uv run python -m app.seed

rebuilds the database named by DATABASE_URL, and only if it is a local SQLite file or the
dedicated `scat_console_dev` PostgreSQL database.

Ids are generated by the database. Tests rely on the insertion order below (the first
I033 row is id 1, and so on), so add new rows at the end of their table's inserts.
"""

from datetime import UTC, date, datetime, timedelta

from sqlalchemy import create_engine, make_url
from sqlalchemy.engine import Connection

from . import tables as t

DEV_DATABASE = "scat_console_dev"
T0 = datetime(2026, 11, 12, 2, 0, tzinfo=UTC)
D13 = date(2026, 11, 13)
D14 = date(2026, 11, 14)


def _i033(conn, airline, flt_nbr, actdate, status, pax: dict, **overrides):
    values = {
        "airline": airline,
        "flt_nbr": flt_nbr,
        "actdate": actdate,
        "status": status,
        "created_by": "dify-extraction",
        "created_at": T0,
        **overrides,
    }
    for slot, count in pax.items():
        values[slot] = slot.upper()
        values[f"pax_{slot}"] = count
    conn.execute(t.i033.insert().values(values))


def _i034(conn, airline, flt_nbr, actdate, status, cls, spml_id, qnty, **overrides):
    conn.execute(
        t.i034.insert().values(
            {
                "airln": airline,
                "fltnr": flt_nbr,
                "acdate": actdate,
                "status": status,
                "secnr": 1,
                "version_no": 1,
                "class": cls,
                "spml_id": spml_id,
                "qnty": qnty,
                **overrides,
            }
        )
    )


def _email(conn, airline, status, subject, body):
    conn.execute(
        t.email.insert().values(
            eml_uri=f"synthetic/{subject}.eml",
            sender=f"catering.ops@{airline.lower()}.example",
            subject=subject,
            received_at=T0,
            body_preview=body,
            airline=airline,
            detected_status=status,
            confidence=0.97,
            pipeline_status="PROCESSED_OK",
            extracted_at=T0,
        )
    )


def _review(conn, error_code, airline, flt_nbr, actdate, status, i033_id, message, **extra):
    conn.execute(
        t.review_item.insert().values(
            error_code=error_code,
            airline=airline,
            flt_nbr=flt_nbr,
            actdate=actdate,
            sector_nbr=1,
            status=status,
            i033_id=i033_id,
            message=message,
            created_at=T0,
            **extra,
        )
    )


def _send(conn, airline, flt_nbr, actdate, status, state, **extra):
    conn.execute(
        t.sap_send.insert().values(
            airline=airline,
            flt_nbr=flt_nbr,
            actdate=actdate,
            status=status,
            state=state,
            release_mode="MANUAL",
            decided_by="synthetic.user",
            decided_at=T0 + timedelta(hours=3),
            **extra,
        )
    )


